export function mergeLandscapeIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...LANDSCAPE_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

