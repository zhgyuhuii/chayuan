export function mergeSurveyExtIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...SURVEY_EXT_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

