export function mergeMilSafetyIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...MILSAFETY_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

