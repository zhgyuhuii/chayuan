/** ET（表格端）与未编制配方共用：按 mode 生成通用分步说明 */
export function buildDefaultManual(recipe) {
  const mode = recipe?.mode === 'send' ? 'send' : 'prefill'
  const name = recipe?.label || '该助手'
  if (mode === 'send') {
    return M(
      `打开目标表格/演示稿，确认它是当前活动文档（${name}会直接读取它）`,
      [
        '点击助手条目右侧的 ▶ 执行按钮，立即发送，无需补充信息',
        '智能体自动读取当前文档并开始分析/处理',
        '只读类助手直接输出结果报告；涉及修改的会先列清单等你确认',
        '对结果不满意可直接在对话里追问调整'
      ],
      ['该助手为直接执行型：点击即运行，适合先看结果再决定下一步']
    )
  }
  return M(
    '想清楚要让助手做什么、需要准备哪些材料或数据',
    [
      '点击助手条目右侧的 ▶ 执行按钮，配方提示词自动填入输入框',
      '在提示词末尾补充你的具体要求（光标处直接输入）',
      '点击发送，智能体开始执行；写回操作先弹预览，确认后生效',
      '对结果不满意可在对话里继续描述调整'
    ],
    ['可在 设置→助手管理 中修改该助手的名称、提示词与触发方式']
  )
}

/** 取助手说明书：优先用编制稿，缺省走生成器。返回 {prep, steps, tips} */
export function getHostAssistantManual(recipe) {
  if (!recipe?.id) return null
  const custom = WPP_ASSISTANT_MANUALS[recipe.id]
  return custom || buildDefaultManual(recipe)
}
