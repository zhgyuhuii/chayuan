export function mergeDrivingSchoolIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...DRIVINGSCHOOL_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

