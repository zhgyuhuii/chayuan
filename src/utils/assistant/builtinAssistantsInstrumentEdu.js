export function mergeInstrumentEduIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...INSTRUMENTEDU_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

