export function mergeRedwoodIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...REDWOOD_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

