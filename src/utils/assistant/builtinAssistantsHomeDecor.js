export function mergeHomeDecorIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...HOMEDECOR_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

