export function mergeGovPersonnelIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...GOVPERSONNEL_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

