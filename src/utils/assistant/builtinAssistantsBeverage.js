export function mergeBeverageIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...BEVERAGE_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

