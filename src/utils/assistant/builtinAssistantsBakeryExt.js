export function mergeBakeryExtIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...BAKERY_EXT_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

