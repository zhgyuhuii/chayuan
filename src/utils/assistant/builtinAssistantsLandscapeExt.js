export function mergeLandscapeExtIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...LANDSCAPE_EXT_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

