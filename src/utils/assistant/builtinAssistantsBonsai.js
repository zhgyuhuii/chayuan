export function mergeBonsaiIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...BONSAI_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

