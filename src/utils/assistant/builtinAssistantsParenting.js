export function mergeParentingIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...PARENTING_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

export default { PARENTING_BUILTIN_ASSISTANTS }
