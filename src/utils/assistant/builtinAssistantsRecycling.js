export function mergeRecyclingIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...RECYCLING_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

