export function mergeExamPrepIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...EXAMPREP_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

