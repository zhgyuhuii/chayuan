export function mergeTcmClinicExtIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...TCMCLINIC_EXT_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

