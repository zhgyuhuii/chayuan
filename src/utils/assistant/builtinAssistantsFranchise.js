export function mergeFranchiseIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...FRANCHISE_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

