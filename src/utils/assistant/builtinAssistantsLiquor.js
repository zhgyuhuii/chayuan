export function mergeLiquorIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...LIQUOR_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

