export function mergeConfinementIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...CONFINEMENT_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

