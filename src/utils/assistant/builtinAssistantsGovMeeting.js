export function mergeGovMeetingIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...GOVMEETING_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

