export function mergeGovPeopleExtIntoBuiltins(b = []) {
  const ids = new Set(b.map((x) => x && x.id))
  return [...b, ...GOVPEOPLE_EXT_BUILTIN_ASSISTANTS.filter((x) => x && !ids.has(x.id))]
}

